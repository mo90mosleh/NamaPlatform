export function findProductHelp(question:string):ProductHelpTopic|null{
 const q=normalizedHelpQuestion(question);
 // A contextual request for the records of the current card takes precedence
 // over generic platform documentation, unless the question explicitly asks
 // how a visual feature (such as chart coloring) operates.
 const contextual=/(?:^|\s)(?:این|همین|اون|آن|انتخاب شده)\s+(?:سمت|واحد|دپارتمان|فرآیند|فرایند|شاخص|کارت)(?:\s|$)/.test(q)
  && !/(?:رنگ|چارت|نمایش|چطور کار می کند)/.test(q);
 if(contextual)return null;
 return topics.find(topic=>topic.test.test(q))??null;
}
export type QuestionIntent='product'|'entity'|'general';
export function classifyQuestionIntent(question:string,history:string[]=[]):QuestionIntent{
 if(findProductHelp(question))return 'product';
 const q=normalizedHelpQuestion(question);
 if(/(?:این|همین|اون|آن|انتخاب شده)\s+(?:سمت|واحد|دپارتمان|فرایند|فرآیند|شاخص|کارت|مدل|سند|بخش)|(?:مالکش|هدفش|فرمولش|دیاگرامش|اسنادش|مراحلش|مسئولش)|(?:مرتبط با این|مربوط به این)/.test(q))return 'entity';
 // A short elliptical follow-up can refer to the last explicitly scoped question.
 if(/^(?:و|پس|حالا)?\s*(?:فرمول|مالک|مسئول|نقش ها|مراحل|ورودی|خروجی|بفرست|باز کن|لینکش)(?:ش| رو| را)?$/.test(q)
  &&history.some(x=>/(?:این|همین|انتخاب شده)\s+(?:فرایند|فرآیند|واحد|سمت|شاخص)/.test(normalizedHelpQuestion(x))))return 'entity';
 return 'general';
}
